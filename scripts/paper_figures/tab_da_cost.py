"""Table for Sec. 7.4 (task E5): cost and memory of the dense and per-site filters, 2D KS.

Per size: latent dimension d; filter-only peak RSS (peak RSS minus peak after the truth is
generated) from the post-fix memory runs `da2d_M_*` (local and dense-GC, N = 64), or from a
post-fix run of the same configuration where no M run exists (`da2d_D6_*`, `da2d_D7_*`); the
memory of one dense d x d float64 matrix; whole-run CPU time (user + sys, includes the PDE truth
integration) from the `/usr/bin/time -l` file of the Block A/C runs. Writes
docs/paper1/tables/tab_da_cost.tex and artifacts/experiments/da2d/cost_summary.json.
"""
import json
import re

from _style import EXP, ROOT

D = EXP / "da2d"
SIZES = [44, 66, 88, 220, 330, 440]


def jl(tag):
    p = D / f"da2d_{tag}.json"
    return json.loads(p.read_text()) if p.exists() else None


def cpu(tag):
    p = D / f"da2d_{tag}.time"
    if not p.exists():
        return None
    t = p.read_text()
    u, s = re.search(r"([\d.]+) user", t), re.search(r"([\d.]+) sys", t)
    return float(u[1]) + float(s[1]) if u and s else None


def filter_rss(cands):
    for tag in cands:
        d = jl(tag)
        if d and "peak_rss_after_truth_GB" in d:
            return d["peak_rss_GB"] - d["peak_rss_after_truth_GB"], tag
    return None, None


rows, rec = [], {}
for L in SIZES:
    pre = "A" if L <= 88 else "C"
    dlat = {44: 384, 66: 864, 88: 1536}.get(L, 6 * (L * 8 // 44) ** 2 // 1)
    loc_rss, loc_src = filter_rss([f"M_L{L}_local_N64_s0", f"D6_L{L}_local_N64_s0", f"D7_L{L}_local_N64_s1"])
    den_rss, den_src = filter_rss([f"M_L{L}_denseGC_N64_s0"])
    c_loc, c_den = cpu(f"{pre}_L{L}_local_N64_s0"), cpu(f"{pre}_L{L}_denseGC_N64_s0")
    dense_matrix_gb = dlat ** 2 * 8 / 2**30
    rec[L] = {"d": dlat, "local_filter_rss_GB": loc_rss, "local_rss_source": loc_src,
              "dense_filter_rss_GB": den_rss, "dense_rss_source": den_src,
              "dense_dxd_matrix_GB": dense_matrix_gb, "cpu_local_s": c_loc, "cpu_denseGC_s": c_den}
    f = lambda x, fmt: (fmt.format(x) if x is not None else "---")  # noqa: E731
    rows.append(f"${L}^2$ & {dlat} & {f(loc_rss, '{:.2f}')} & {f(den_rss, '{:.2f}')} & {dense_matrix_gb:.3g} & "
                f"{f(c_loc, '{:.0f}')} & {f(c_den, '{:.0f}')} \\\\")
(ROOT / "docs/paper1/tables/tab_da_cost.tex").write_text(
    "% Generated by scripts/paper_figures/tab_da_cost.py -- do not edit by hand.\n" + "\n".join(rows) + "\n")
(D / "cost_summary.json").write_text(json.dumps(rec, indent=2))
print("\n".join(rows))
