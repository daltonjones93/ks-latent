"""Table for Sec. 7.8 (task K2e): cost of the Part II latent filter (p7c12d10_ks2d), 2D KS, 64 members
per tiling, observation stride 8, 100 cycles, one and four tilings, one run at a time on a quiet machine
(I14, scripts/run_i7_i16_i14_j5.sh; 3 threads; free run off).

Per size: latent dimension per tiling; whole-run wall time (includes the PDE truth integration and the
observation draws, which the tilings share); the ratio of four tilings to one in one process; peak
resident memory of the whole run; and the size of the stored truth trajectory (501 float64 snapshots),
which that peak includes. Writes docs/paper1/tables/tab_da_cost.tex and
artifacts/experiments/da2d/cost_summary.json.
"""
import json

from _style import EXP, write_table

D = EXP / "da2d"
SIZES = [44, 88, 220, 330, 440]
NX = {44: 128, 88: 256, 220: 640, 330: 960, 440: 1280}
rows, summ = [], []
for L in SIZES:
    r = {T: json.loads((D / f"h9_I14_L{L}_T{T}.json").read_text()) for T in (1, 4)}
    d = (NX[L] // 16) ** 2 * 12
    w1, w4 = r[1]["wall_s"], r[4]["wall_s"]
    m1, m4 = r[1]["steady"]["peak_rss_GB"], r[4]["steady"]["peak_rss_GB"]
    truth = NX[L] ** 2 * 501 * 8 / 1e9
    summ.append({"L": L, "d_lat": d, "wall_T1": w1, "wall_T4": w4, "rss_T1": m1, "rss_T4": m4, "truth_GB": truth,
                 "blend": r[4]["steady"]["blend"]})
    rows.append(f"${L}^2$ & ${d:,}$ & ${w1:.0f}$ & ${w4:.0f}$ & ${w4 / w1:.1f}$ & ${w4 / 100:.2f}$ & ${m1:.1f}$ & ${m4:.1f}$ & "
                f"${truth:.2f}$ \\\\".replace(",", "\\,"))
write_table("tab_da_cost", "% Generated by scripts/paper_figures/tab_da_cost.py -- do not edit by hand.\n" + "\n".join(rows) + "\n",
            [f"artifacts/experiments/da2d/h9_I14_L{L}_T{T}.json" for L in NX for T in (1, 4)])
(D / "cost_summary.json").write_text(json.dumps(summ, indent=2))
print("\n".join(rows))
