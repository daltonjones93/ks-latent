"""Table for Sec. 7.3 (task E4): 1D data assimilation after transfer at a fixed observation
spacing (3.125 units), steady-state skill (cycles 51-100), from the D1/D3 runs:
artifacts/da_pff_ltransfer_d1_{pff,letkf}_L{200,400}_{none,gaspari_cohn}_nens{N}.json and
artifacts/e3_sec_vs_gc_ltransfer_d3_L200_{pff_sec_psd,serial_sec_enkf_none}_N{N}.json, and the kernel particle
flow filter of Hu & van Leeuwen (2021) (Z20 E7, alpha 0.1, no RTPS):
artifacts/da_pff_ltransfer_z20_e7_kpff_L{200,400}_{none,gaspari_cohn}_N{N}.json. The "pff" runs are the
Gauss-Newton particle flow filter (GN-PFF; ks_latent/da/pff.py). Writes docs/paper1/tables/tab07_1d_da.tex."""
import json

from _style import ART, write_table

NS = [8, 16, 32, 64, 128, 256]


def sk(path):
    p = ART / path
    return json.loads(p.read_text())["skill_steady"] if p.exists() else None


def f(x):
    return "---" if x is None else f"{x:.2f}"


rows = ["% Generated by scripts/paper_figures/tab07_1d_da.py -- do not edit by hand."]
for N in NS:
    cells = []
    for meth in ("pff", "kpff", "letkf"):
        for L in (200, 400):
            if meth == "kpff":
                a = sk(f"da_pff_ltransfer_z20_e7_kpff_L{L}_none_N{N}.json")
                b = sk(f"da_pff_ltransfer_z20_e7_kpff_L{L}_gaspari_cohn_N{N}.json")
            else:
                a = sk(f"da_pff_ltransfer_d1_{meth}_L{L}_none_nens{N}.json")
                b = sk(f"da_pff_ltransfer_d1_{meth}_L{L}_gaspari_cohn_nens{N}.json")
            cells.append(f"{f(a)} / {f(b)}")
    cells.append(f(sk(f"e3_sec_vs_gc_ltransfer_d3_L200_pff_sec_psd_N{N}.json")))
    cells.append(f(sk(f"e3_sec_vs_gc_ltransfer_d3_L200_serial_sec_enkf_none_N{N}.json")))
    rows.append(f"{N} & " + " & ".join(cells) + " \\\\")
write_table("tab07_1d_da", "\n".join(rows) + "\n",
            ["artifacts/da_pff_ltransfer_z20_e7_kpff_L{200,400}_{none,gaspari_cohn}_N{N}.json",
             "artifacts/da_pff_ltransfer_d1_{pff,letkf}_L{200,400}_{none,gaspari_cohn}_nens{N}.json",
             "artifacts/e3_sec_vs_gc_ltransfer_d3_L200_{pff_sec_psd,serial_sec_enkf_none}_N{N}.json"])
print("\n".join(rows))
