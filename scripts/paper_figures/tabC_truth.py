"""Appendix C tables (task B14), generated from the truth-run JSONs.

  docs/paper1/tables/tabC_running_kolm.tex  running D_KY of every 120-unit Kolmogorov run that
                                            recorded it (+ deviation of the 40-unit value)
  docs/paper1/tables/tabC_running_ks2d.tex  running D_KY of the 2D KS runs that recorded it
                                            (+ change over the last 20 time units)
  docs/paper1/tables/tabC_truth_runs.tex    every truth run used in the paper
1D runs that differ only in the number of tangent directions follow the same trajectory and give
the same D_KY to within 0.01; they are listed once (largest K). New runs (task A3) appear
automatically when their JSONs exist.
"""
import glob
import json

from _style import EXP, ROOT
from _truths import REGISTRY, runs

OUT = ROOT / "docs/paper1/tables"


def load(p):
    return json.loads(open(p).read())


# ---------- running D_KY, Kolmogorov ----------
lines = ["% Generated by scripts/paper_figures/tabC_truth.py -- do not edit by hand."]
stats = []
for f in sorted(glob.glob(str(EXP / "crop/truth_*_T120.json"))):
    d = load(f)
    r = d.get("running_D_KY_by_time")
    if not r:
        continue
    alpha = d["alpha"]; sc = d["scale"]; seed = d["seed"]
    vals = [r[k] for k in sorted(r, key=float)]
    dev = 100 * (r[[k for k in r if float(k) == 40.0][0]] / d["D_KY"] - 1)
    stats.append(dev)
    lines.append(f"$\\alpha={alpha:g}$, ${sc}\\times$, seed {seed} & " + " & ".join(f"{v:.1f}" for v in vals)
                 + f" & ${dev:+.1f}\\%$ \\\\")
(OUT / "tabC_running_kolm.tex").write_text("\n".join(lines) + "\n")
kolm_summary = {"n": len(stats), "min": min(stats), "max": max(stats), "mean": sum(stats) / len(stats),
                "n_high": sum(1 for s in stats if s > 0)}

# ---------- running D_KY, 2D KS ----------
lines = ["% Generated by scripts/paper_figures/tabC_truth.py -- do not edit by hand."]
for f in sorted(glob.glob(str(EXP / "truth_ks2d/truth_ks2d_*.json"))):
    d = load(f)
    r = d["running_D_KY_by_time"]
    vals = [r[k] for k in sorted(r, key=float)]
    last20 = 100 * (vals[-1] / r[[k for k in r if float(k) == 20.0][0]] - 1)
    lines.append(f"${d['L']:g}^2$, seed {d['seed']} & " + " & ".join(f"{v:.1f}" for v in vals)
                 + f" & ${last20:+.1f}\\%$ \\\\")
(OUT / "tabC_running_ks2d.tex").write_text("\n".join(lines) + "\n")

# ---------- all truth runs ----------
lines = ["% Generated by scripts/paper_figures/tabC_truth.py -- do not edit by hand."]
S = load(EXP / "e1_model/summary_1d_transfer.json")
first = True
for L in ["25", "50", "100", "200", "400"]:
    for rz in S["truth"][L]["realizations"]:
        files = rz["files"]
        if "Gate 1" in files[0]:
            K, lam, npos = 35, 0.0899, 12
        else:
            ds = [load(ROOT / f) for f in files]
            dd = max(ds, key=lambda x: x["n_directions"])
            K, lam, npos = dd["n_directions"], dd["lambda1"], dd["n_positive"]
        lines.append(f"{'1D KS' if first else ''} & $L={L}$ & --- & {K} & {int(rz['total_time'])} & "
                     f"{lam:.3f} & {npos} & {rz['D_KY']:.2f} \\\\")
        first = False
lines.append("\\hline")
LABEL = {"ks2d": "2D KS", "kolm0.1": "Kolm., $\\alpha=0.1$", "kolm0.05": "Kolm., $\\alpha=0.05$",
         "kolm0.025": "Kolm., $\\alpha=0.025$"}
prev = None
for (sysname, size) in REGISTRY:
    if prev is not None and sysname != prev:
        lines.append("\\hline")
    rs = runs(sysname, size)
    for k, r in enumerate(rs):
        size_txt = (f"${44 * size:g}^2$" if sysname == "ks2d" else f"${size}\\times$")
        lines.append(f"{LABEL[sysname] if (sysname != prev and k == 0) else ''} & {size_txt} & {r['seed']} & "
                     f"{r['n_directions']} & {int(r['total_time'])} & {r['lambda1']:.3f} & {r['n_positive']} & "
                     f"{r['D_KY']:.2f} \\\\")
        prev = sysname
(OUT / "tabC_truth_runs.tex").write_text("\n".join(lines) + "\n")
(EXP / "tabC_kolm_running_summary.json").write_text(json.dumps(kolm_summary, indent=2))
print("Kolmogorov 40- vs 120-unit deviations:", kolm_summary)
print((OUT / "tabC_running_ks2d.tex").read_text())
