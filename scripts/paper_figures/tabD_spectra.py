"""Appendix D table (task A6): reconstruction error, field amplitude and band energy shares
for truth / free-running model / reconstruction, from artifacts/experiments/spectra/*.json
(scripts/eval_spectra_recon.py). Writes docs/paper1/tables/tabD_spectra.tex."""
import json

from _style import EXP, ROOT

OUT = ROOT / "docs/paper1/tables"
rows, inputs = [], []
NAMES = {"ks1d": ("1D KS", lambda s: f"$L={100*s:g}$"), "ks2d": ("2D KS", lambda s: f"${44*s:g}^2$"),
         "kolm": (r"Kolm., $\alpha=0.1$", lambda s: f"${s:g}\\times$")}
for sysname, scales in (("ks1d", (1, 2, 4)), ("ks2d", (1, 1.5, 2)), ("kolm", (1, 2, 3))):
    for i, s in enumerate(scales):
        f = EXP / f"spectra/{sysname}_x{s:g}.json"
        d = json.loads(f.read_text()); inputs.append(str(f.relative_to(ROOT)))
        b = d["band_ratio_model_over_truth"]; br = d["band_ratio_recon_over_truth"]
        tot_t = sum(x["energy_ref"] for x in b); tot_r = sum(x["energy_ref"] for x in br)
        low_t, low_m = 100 * b[0]["energy_ref"] / tot_t, 100 * b[0]["energy_other"] / tot_t
        hi_t, hi_r = 100 * br[-1]["energy_ref"] / tot_r, 100 * br[-1]["energy_other"] / tot_r
        label, sz = NAMES[sysname]
        rows.append(f"{label if i == 0 else ''} & {sz(s)} & ${100*d['recon_mse_over_field_variance']:.2f}$ & "
                    f"${d['field_std_model']/d['field_std_truth']:.2f}$ & ${low_t:.2f}$ / ${low_m:.2f}$ & "
                    f"${hi_t:.3f}$ / ${hi_r:.3f}$ \\\\")
    rows.append("\\hline")
(OUT / "tabD_spectra.tex").write_text("% Generated by scripts/paper_figures/tabD_spectra.py -- do not edit by hand.\n"
                                      + "\n".join(rows[:-1]) + "\n")
print((OUT / "tabD_spectra.tex").read_text())
