"""Appendix E tables (task E6): observation networks and the inflation sweep.

tabE_networks.tex: per DA configuration, domain, grid, sites, latent dimension, observation
  stride and spacing, number of observations (from the run JSONs where recorded, else computed
  from the same geometry the scripts use).
tabE_inflation.tex: steady-state skill (calibration) vs multiplicative inflation, 44^2, N = 64.
"""
import json
import statistics as st

from _style import ART, EXP, write_table

D = EXP / "da2d"


def steady(tag):
    p = D / f"da2d_{tag}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    fr, da, sp = d["rmse_free_per_cycle"], d["rmse_da_per_cycle"], d["spread_per_cycle"]
    late = slice(len(da) // 2, None)
    return (st.mean(f / a for f, a in zip(fr[late], da[late])), st.mean(s / a for s, a in zip(sp[late], da[late])))


rows = ["% Generated by scripts/paper_figures/tabE_da.py -- do not edit by hand."]
for L in (200, 400):
    d = json.loads((ART / f"da_pff_ltransfer_d1_pff_L{L}_gaspari_cohn_nens64.json").read_text())
    m = d["new_NX"] // d["obs_stride"]
    rows.append(f"1D KS & $L={L}$ & {d['new_NX']} & {d['new_n_sites']} & {d['new_n_sites'] * 3} & "
                f"{d['obs_stride']} & {d['obs_spacing_units']:.3f} & {m} \\\\")
for L, pre in ((44, "A"), (66, "A"), (88, "A"), (220, "C"), (330, "C"), (440, "C")):
    d = json.loads((D / f"da2d_{pre}_L{L}_local_N64_s0.json").read_text())
    m = (d["NX"] // d["obs_stride_x"]) ** 2
    rows.append(f"2D KS & ${L}^2$ & ${d['NX']}^2$ & ${d['n_sites']}^2$ & {d['d_latent']} & {d['obs_stride_x']} & "
                f"{d['obs_stride_x'] * d['dx']:.3f} & {m} \\\\")
write_table("tabE_networks", "\n".join(rows) + "\n")
print("\n".join(rows))

rows = ["% Generated by scripts/paper_figures/tabE_da.py -- do not edit by hand."]
for name, base, pat in (("unlocalized", "A_L44_denseNone_N64_s0", "D5_L44_denseNone_N64_inf{}_s0"),
                        ("dense GC", "A_L44_denseGC_N64_s0", "D5_L44_denseGC_N64_inf{}_s0"),
                        ("per-site", "A_L44_local_N64_s0", "D5_L44_local_N64_inf{}_s0")):
    cells = [steady(base)] + [steady(pat.format(i)) for i in ("1.05", "1.1", "1.2")]
    rows.append(f"{name} & " + " & ".join(f"{c[0]:.2f} ({c[1]:.2f})" for c in cells) + " \\\\")
write_table("tabE_inflation", "\n".join(rows) + "\n")
print("\n".join(rows))
