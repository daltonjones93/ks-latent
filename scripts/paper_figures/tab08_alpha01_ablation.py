"""Table VIII (Sec. 8.4): the alpha=0.1 training variants. Settings from the checkpoints,
truth-free selection statistics from artifacts/experiments/a10_selection/ (task A10), and
errors against the truth registry (mean of per-IC |relative errors|, 3 ICs per size).
Paper names v1-v6 = record tags k_xs01, _v2, _v3, _v4, _v5, _v7 (record v6a was bit-identical
to v5 and is omitted).
Writes docs/paper1/tables/tab08_alpha01_ablation.tex."""
import json

import numpy as np
import torch

from _style import ART, EXP, MAIN_A01, write_table
from _truths import runs

TAGS = ["k_xs01", "k_xs01_v2", "k_xs01_v3", "k_xs01_v4", "k_xs01_v5", "k_xs01_v7"]
dec = json.loads((EXP / "a10_selection/decision.json").read_text())
cand = {c["tag"]: c for c in dec["candidates"]}
T = {s: np.mean([r["D_KY"] for r in runs("kolm0.1", s)]) for s in (1, 2, 3)}
lines = ["% Generated by scripts/paper_figures/tab08_alpha01_ablation.py -- do not edit by hand."]
for i, tag in enumerate(TAGS):
    ae = torch.load(ART / f"stage1_ae_kolmogorov_crop_{tag}.pt", map_location="cpu", weights_only=False)
    pr = torch.load(ART / f"stage2_prop_kolmogorov_crop_{tag}.pt", map_location="cpu", weights_only=False)
    ca, cp = ae["crop_ae_config"], pr["crop_prop_config"]
    errs = []
    for s in (1, 2, 3):
        v = [json.loads((EXP / f"crop/{tag}_x{s}_seed{k}.json").read_text())["model_D_KY"] for k in range(3)]
        errs.append(100 * np.mean([abs(x - T[s]) / T[s] for x in v]))
    c = cand[tag]
    name = f"v{i + 1}" + ("$^\\star$" if tag == MAIN_A01 else "") + ("$^\\dagger$" if cp.get("w_rank", 0) else "")
    lines.append(f"{name} & {cp['k_max']} & {ca.get('logdet_eps', 1e-3):g} & {ca['w_var']:g} / {ca['w_logdet']:g} & "
                 f"{c['val_k8']:.4f} & {100*c['max_abs_deviation']:.1f} & "
                 + " & ".join(f"{e:.1f}" for e in errs) + " \\\\")
write_table("tab08_alpha01_ablation", "\n".join(lines) + "\n", main_alpha01_model=MAIN_A01)
print("\n".join(lines))
