"""Appendix E, Part II robustness (Block K2f, 2026-10-10; tasks I16, K10a), 44^2 unless stated, 4 tilings,
steady-state analysis error (field units) and spread/error. Rows: initial ensemble (encoded truth vs an
independent climatology; cycles until the error first falls within 10% of its steady value); assumed observation
error 0.5x / 1x / 2x the true one; RTPS 0.5 / 0.7 / 0.9; long runs (300 cycles at 220^2, stride 8; 300 cycles at
44^2, stride 16), as means over cycles 51-100, 101-200, 201-300. Missing runs print as ---.
Writes tables/tabE_p2_robustness.tex (+ .meta.json).
"""
import json

import numpy as np

from _style import EXP, ROOT

D = EXP / "da2d"
inputs = []


def L(tag):
    p = D / f"h9_{tag}.json"
    if not p.exists():
        return None
    inputs.append(str(p.relative_to(ROOT)))
    return json.loads(p.read_text())


def row(lab, tag, extra=""):
    d = L(tag)
    if d is None:
        return f"{lab} & --- & --- & {extra or '---'} \\\\"
    s = d["steady"]
    return f"{lab} & {s['blend']:.3f} & {s['calib_blend']:.2f} & {extra or '---'} \\\\"


def settle(tag):
    d = L(tag)
    if d is None:
        return "---"
    e = np.array(d["per_cycle"]["blend"]); st = d["steady"]["blend"]
    return str(int(np.argmax(e <= 1.1 * st)) + 1)


def blocks(tag):
    d = L(tag)
    if d is None:
        return "---"
    e = np.array(d["per_cycle"]["blend"])
    return " / ".join(f"{e[a:b].mean():.2f}" for a, b in ((50, 100), (100, 200), (200, 300)) if len(e) >= b)


rows = ["% Generated by scripts/paper_figures/tabE_p2_robustness.py -- do not edit by hand.",
        "\\multicolumn{4}{l}{\\emph{initial ensemble} (last column: cycles to within 10\\% of steady state)} \\\\",
        row("encoded truth + noise", "I33_d10_T4_s0", settle("I33_d10_T4_s0")),
        row("climatology, 4 tilings", "I16a_clim_T4", settle("I16a_clim_T4")),
        row("climatology, 1 tiling", "I16a_clim_T1", settle("I16a_clim_T1")),
        "\\hline", "\\multicolumn{4}{l}{\\emph{assumed observation error}} \\\\",
        row("$0.5\\times$ true", "I16b_R0.5x_T4"), row("$1\\times$ true", "I33_d10_T4_s0"), row("$2\\times$ true", "I16b_R2x_T4"),
        "\\hline", "\\multicolumn{4}{l}{\\emph{RTPS weight}} \\\\",
        row("0.5", "D10_L44_rtps0.5"), row("0.7", "I33_d10_T4_s0"), row("0.9", "D10_L44_rtps0.9"),
        "\\hline", "\\multicolumn{4}{l}{\\emph{long runs} (last column: means over cycles 51--100 / 101--200 / 201--300)} \\\\",
        row("$220^2$, stride 8, 300 cycles", "I16c_L220_300cyc_T4", blocks("I16c_L220_300cyc_T4")),
        row("$44^2$, stride 16, 300 cycles", "K10a_st16_T4_300", blocks("K10a_st16_T4_300"))]
out = ROOT / "docs/paper1/tables/tabE_p2_robustness.tex"
out.write_text("\n".join(rows) + "\n")
out.with_suffix(".meta.json").write_text(json.dumps({"inputs": sorted(set(inputs))}, indent=2))
print("\n".join(rows))
