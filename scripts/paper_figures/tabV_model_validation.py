"""Paper II (S4.6): validation of the 12-channel 2D KS models used for data assimilation.

Rows: the noisy-trained model (p7c12d10, the model of every Paper II experiment) and its
clean-trained sibling (p7c12), at 44^2 and 66^2. Columns: the model's D_KY, lambda_1 and n_+
(one initial condition, seed 0; artifacts/experiments/crop/<tag>_ks2d_x<scale>_seed0.json) with
the relative error against the seed-0 truth (the matched initial condition); the truth runs'
range (scripts/paper_figures/_truths.py); and free-rollout statistics against the true PDE from
the same initial conditions (seeds 0 and 1, steps 100-1000; field std and the energy share at
|k| >= 1.4; artifacts/experiments/rollout_stats/<tag>_ks2d_n1000.json, truth from the p7b run file,
which integrates the PDE from the same initial conditions).
Writes <PAPER_TABLES>/model_validation.tex (+ .meta.json). Paper II only.
"""
import json

import numpy as np

from _style import EXP, write_table
from _truths import runs

MODELS = [("noisy-trained", "p7c12d10_ks2d"), ("clean-trained", "p7c12_ks2d")]
SIZES = [(1.0, "1", "44^2"), (1.5, "1.5", "66^2")]
RS = EXP / "rollout_stats"
TRUTH_ROLL = json.loads((RS / "p7b_ks2d_ks2d_n1000.json").read_text())["runs"]
inputs = [str((RS / "p7b_ks2d_ks2d_n1000.json").relative_to(EXP.parent.parent))]


def roll_stats(runs_, scale_key, who):
    std, hi = [], []
    for seed in (0, 1):
        r = runs_[f"{scale_key}_seed{seed}"][who]
        std.append(r["std_late"])
        hi.append(r["band_shares_late"][-1])
    return np.mean(std), 100 * np.mean(hi)


rows = []
for i, (label, tag) in enumerate(MODELS):
    roll = json.loads((RS / f"{tag}_ks2d_n1000.json").read_text())["runs"]
    inputs.append(f"artifacts/experiments/rollout_stats/{tag}_ks2d_n1000.json")
    if i:
        rows.append("\\hline")
    for j, (sc, sk, lab) in enumerate(SIZES):
        f = EXP / "crop" / f"{tag}_x{sc:.1f}_seed0.json"
        inputs.append(str(f.relative_to(EXP.parent.parent)))
        m = json.loads(f.read_text())
        tr = runs("ks2d", sc)
        inputs += [r["file"] for r in tr]
        t0 = next(r for r in tr if r["seed"] == 0)
        err = 100 * (m["model_D_KY"] - t0["D_KY"]) / t0["D_KY"]
        dk = [r["D_KY"] for r in tr]
        l1 = [r["lambda1"] for r in tr]
        npos = [r["n_positive"] for r in tr]
        ms, mh = roll_stats(roll, sk, "model")
        ts, th = roll_stats(TRUTH_ROLL, sk, "truth")
        rows.append(
            f"{label if j == 0 else ''} & ${lab}$ & ${m['model_D_KY']:.1f}$ & ${err:+.1f}\\%$ & "
            f"${min(dk):.1f}$--${max(dk):.1f}$ & ${m['model_lambda1']:.3f}$ & "
            f"${min(l1):.3f}$--${max(l1):.3f}$ & ${m['model_n_positive']}$ & ${min(npos)}$--${max(npos)}$ & "
            f"${ms:.2f}$ / ${ts:.2f}$ & ${mh:.2f}$ / ${th:.2f}$ \\\\")

write_table("tabV_p2_model_validation",
            "% Generated by scripts/paper_figures/tabV_model_validation.py -- do not edit by hand.\n"
            + "\n".join(rows) + "\n", sorted(set(inputs)))
