"""Tables II (ground truth) and III (1D transfer), generated from artifacts.

Table II: 1D rows from artifacts/experiments/e1_model/summary_1d_transfer.json (all truth
realizations per L); 2D rows from `_truths.py` (run JSONs). Table III: model rows from the
same summary (section224, standardized ICs, 3 ICs per size).
Writes docs/paper1/tables/tab02_truth.tex and tab03_transfer1d.tex (+ .meta.json each).
"""
import json

import numpy as np

from _style import EXP, write_table
from _truths import runs

S = json.loads((EXP / "e1_model/summary_1d_transfer.json").read_text())


def fmt_runs(vals, nd=2):
    return ",\\,".join(f"{v:.{nd}f}" for v in vals)


# ---------------- Table II ----------------
rows, inputs = [], ["artifacts/experiments/e1_model/summary_1d_transfer.json"]
for i, L in enumerate([25, 50, 100, 200, 400]):
    t = S["truth"][str(L)]
    T = sorted({int(r["total_time"]) for r in t["realizations"]})
    note = {25: "near onset; $\\lambda_1\\approx0.001$", 100: "trained size"}.get(L, "")
    runs_txt = f"runs: {fmt_runs(t['values'])}" if t["n"] > 1 else ""
    rows.append(f"{'1D KS' if i == 0 else ''} & $L={L}$ & ${t['mean']:.2f}$ & ${t['mean']/L:.3f}$ & "
                f"{'/'.join(map(str, T))} ({t['n']}) & {'; '.join(x for x in (note, runs_txt) if x)} \\\\")
rows.append("\\hline")
for j, (sz, lab, area) in enumerate([(1.0, "44^2", 44.0**2), (1.5, "66^2", 66.0**2)]):
    rs = runs("ks2d", sz); inputs += [r["file"] for r in rs]
    v = [r["D_KY"] for r in rs]
    rows.append(f"{'2D KS' if j == 0 else ''} & ${lab}$ & ${np.mean(v):.2f}$ & ${np.mean(v)/area:.4f}$ & "
                f"40 ({len(v)}) & {('runs: ' + fmt_runs(v)) if len(v) > 1 else ''} \\\\")
for alpha in (0.1, 0.05, 0.025):
    rows.append("\\hline")
    for sc in (1, 2, 3):
        rs = runs(f"kolm{alpha}", sc); inputs += [r["file"] for r in rs]
        v = [r["D_KY"] for r in rs]
        T = "/".join(str(x) for x in sorted({int(r["total_time"]) for r in rs}))
        note = ("matched ICs: " if (alpha == 0.05 and sc == 1) else "runs: ") + fmt_runs(v) if len(v) > 1 else ""
        sysname = ("Kolmogorov, $\\alpha=" + f"{alpha}$") if sc == 1 else ""
        rows.append(f"{sysname} & ${sc}\\times$ & "
                    f"$\\mathbf{{{np.mean(v):.2f}}}$ & ${np.mean(v)/sc:.1f}$ & {T} ({len(v)}) & {note} \\\\")
t2 = write_table("tab02_truth",
    "% Generated by scripts/paper_figures/tab02_tab03.py -- do not edit by hand.\n" + "\n".join(rows) + "\n", inputs)

# ---------------- Table III ----------------
rows = []
for L in [25, 50, 100, 200, 400]:
    m, t = S["model"][str(L)], S["truth"][str(L)]
    P, d = L * 16 // 100, L * 48 // 100
    err = "---" if L == 25 else f"${100 * (m['mean'] - t['mean']) / t['mean']:+.1f}\\%$"
    npos = "/".join(str(x) for x in sorted(set(m["n_positive"])))
    rows.append(f"{L} & {P} & {d} & ${t['mean']:.2f}\\pm{t['half_range']:.2f}$ & "
                f"${m['mean']:.2f}\\pm{m['half_range']:.2f}$ & {npos} & {err} & ${m['mean']/L:.4f}$ \\\\")
t3 = write_table("tab03_transfer1d",
    "% Generated by scripts/paper_figures/tab02_tab03.py -- do not edit by hand.\n" + "\n".join(rows) + "\n",
    ["artifacts/experiments/e1_model/summary_1d_transfer.json"])
print(t2.read_text()); print(t3.read_text())
