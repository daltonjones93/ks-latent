"""Tables for Sec. 7.2 (task E3): 2D KS data assimilation across domain sizes, steady-state
skill (cycles 51-100) and calibration, from artifacts/experiments/da2d/da2d_*.json.

tab07_2d_sizes.tex: one row per size: d, n_+ (truth runs, or the transferred model where no
  truth exists), per-site filter N = 64 (seed 0, and seed 1 where run), dense + GC N = 64,
  unlocalized N = 64 and N = 128.
tab07_2d_ensemble.tex: per-site filter (perturbed-obs / deterministic transform at 44^2) and
  dense + GC against ensemble size, per size.
"""
import json
import statistics as st

import numpy as np

from _style import EXP, ROOT
from _truths import runs

D = EXP / "da2d"


def steady(tag):
    p = D / f"da2d_{tag}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    fr, da, sp = d["rmse_free_per_cycle"], d["rmse_da_per_cycle"], d["spread_per_cycle"]
    late = slice(len(da) // 2, None)
    return (st.mean(f / a for f, a in zip(fr[late], da[late])), st.mean(s / a for s, a in zip(sp[late], da[late])))


def cell(x, cal=True):
    if x is None:
        return "---"
    return f"{x[0]:.2f} ({x[1]:.2f})" if cal else f"{x[0]:.2f}"


def nplus(L):
    if L in (44, 66):
        v = [r["n_positive"] for r in runs("ks2d", {44: 1.0, 66: 1.5}[L])]
        return f"{min(v)}--{max(v)}"
    if L == 88:
        v = [json.loads((EXP / f"crop/p7b_ks2d_x2.0_seed{k}.json").read_text())["model_n_positive"] for k in (0, 1)]
        return f"{min(v)}--{max(v)}$^a$"
    return "---"


SIZES = [44, 66, 88, 220, 330, 440]
rows = ["% Generated by scripts/paper_figures/tab07_2d_da.py -- do not edit by hand."]
summary = {}
for L in SIZES:
    pre = "A" if L <= 88 else "C"
    dlat = 6 * (L * 8 // 44) ** 2
    loc0 = steady(f"{pre}_L{L}_local_N64_s0")
    loc1 = steady(f"A_L{L}_local_N64_s1") or steady(f"D7_L{L}_local_N64_s1")
    gc = steady(f"{pre}_L{L}_denseGC_N64_s0")
    n64 = steady(f"A_L{L}_denseNone_N64_s0")
    n128 = steady(f"A_L{L}_denseNone_N128_s0")
    summary[L] = {"d": dlat, "local_N64_s0": loc0, "local_N64_s1": loc1, "denseGC_N64": gc,
                  "none_N64": n64, "none_N128": n128}
    loc = cell(loc0) + ("" if loc1 is None else f", {loc1[0]:.2f}")
    rows.append(f"${L}^2$ & {dlat} & {nplus(L)} & {loc} & {cell(gc)} & {cell(n64, False)} & {cell(n128, False)} \\\\")
(ROOT / "docs/paper1/tables/tab07_2d_sizes.tex").write_text("\n".join(rows) + "\n")

rows = ["% Generated by scripts/paper_figures/tab07_2d_da.py -- do not edit by hand."]
for N in (8, 16, 32, 64, 128):
    cells = []
    for L in (44, 66, 88, 220):
        pre = "A" if L <= 88 else ("C" if N == 64 else "D8")
        cells.append(cell(steady(f"{pre}_L{L}_local_N{N}_s0"), cal=False))
    cells.append(cell(steady(f"D4_L44_etkf_N{N}_s0"), cal=False))
    for L in (44, 66, 88):
        cells.append(cell(steady(f"A_L{L}_denseGC_N{N}_s0"), cal=False))
    rows.append(f"{N} & " + " & ".join(cells) + " \\\\")
(ROOT / "docs/paper1/tables/tab07_2d_ensemble.tex").write_text("\n".join(rows) + "\n")
(D / "sizes_summary.json").write_text(json.dumps(summary, indent=2))
print((ROOT / "docs/paper1/tables/tab07_2d_sizes.tex").read_text())
print("\n".join(rows))
