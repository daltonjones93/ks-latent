"""Fig. 16 + Table (Blocks K3e, K2h; 2026-10-10): forecasts from the analyses (task I7).

From steady-state analyses at 44^2 (every 5th cycle from cycle 51, 10 starts per seed, seeds 0-2), deterministic
forecasts of each tiling's analysis mean, blended with Eq. (blend); the single-tiling analysis (tiling 0 of the
same runs); a forecast from the encoded TRUE state (the learned model's own forecast limit); persistence of the
blended analysis; climatology (rms of the true field). Error vs lead in DA cycles (0.5 time units) and in
Lyapunov times (truth lambda_1 = 0.165 at 44^2, Table truth). (a) errors, seed mean, range shaded for the blend;
(b) ratio of the blended to the single-tiling forecast error.
Writes figures/fig16_forecasts.pdf and tables/tab07_p2_forecast.tex (+ .meta.json).
"""
import json

import numpy as np

from _style import AQUA, COL1, EXP, INK, INK2, MUTED, ORANGE, ROOT, panel_label, plt, save

D = EXP / "da2d"
LAM1, CYC = 0.165, 0.5
inputs, runs = [], []
for sd in range(3):
    p = D / f"h9_I7_T4_s{sd}.json"
    inputs.append(str(p.relative_to(ROOT)))
    runs.append(json.loads(p.read_text())["forecast"])
keys = ("blend", "tiling0", "true_init_blend", "persistence", "clim")
nl = min(len(r["blend"]) for r in runs)
A = {k: np.array([r[k][:nl] for r in runs]) for k in keys}
lead = np.arange(1, nl + 1)

fig, (a, b) = plt.subplots(2, 1, figsize=(COL1, 3.9), sharex=True, gridspec_kw={"height_ratios": [2.2, 1], "hspace": 0.15})
for k, lab, col, ls in (("blend", "4 tilings", AQUA, "-"), ("tiling0", "1 tiling", INK2, "-"),
                        ("true_init_blend", "from the true state", INK, ":"), ("persistence", "persistence", ORANGE, "--"),
                        ("clim", "field std", MUTED, "-.")):
    m = A[k].mean(0)
    a.plot(lead, m, ls=ls, color=col, lw=1.2, label=lab)
    if k == "blend":
        a.fill_between(lead, A[k].min(0), A[k].max(0), color=AQUA, alpha=0.2, lw=0)
a.set_ylabel("forecast RMSE"); a.set_ylim(0, 6.2)
a.legend(fontsize=6.2, loc="lower right", ncol=1)
top = a.secondary_xaxis("top", functions=(lambda x: x * CYC * LAM1, lambda t: t / (CYC * LAM1)))
top.set_xlabel("lead (Lyapunov times)", fontsize=7.5)
panel_label(a, "a")
r = A["blend"] / A["tiling0"]
b.plot(lead, r.mean(0), color=AQUA); b.fill_between(lead, r.min(0), r.max(0), color=AQUA, alpha=0.2, lw=0)
b.axhline(1, color=INK, lw=0.6, ls=":")
b.set_xlabel("lead (cycles of 0.5 time units)"); b.set_ylabel("4 tilings / 1"); b.set_ylim(0.6, 1.1)
panel_label(b, "b")
save(fig, "fig16_forecasts", inputs)

rows = ["% Generated by scripts/paper_figures/fig16_forecasts.py -- do not edit by hand."]
for L in (1, 5, 10, 20, 40, 60):
    if L > nl:
        continue
    i = L - 1
    cells = [f"{A[k][:, i].mean():.2f}" for k in keys]
    rows.append(f"{L} & {L * CYC * LAM1:.2f} & " + " & ".join(cells) + f" & {(A['blend'][:, i] / A['tiling0'][:, i]).mean():.2f} \\\\")
(ROOT / "docs/paper1/tables/tab07_p2_forecast.tex").write_text("\n".join(rows) + "\n")
(ROOT / "docs/paper1/tables/tab07_p2_forecast.meta.json").write_text(json.dumps({"inputs": inputs}, indent=2))
print("\n".join(rows))
