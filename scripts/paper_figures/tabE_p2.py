"""Appendix E, Part II (Block K2g, 2026-10-10): observation networks of the Part II runs.

tabE_p2_networks.tex: per domain: grid, sites, channels c, latent dimension d per tiling, tilings K and
  their offsets (grid points), observation stride and spacing (length units), number of observations m.
2D KS geometry is the deployment grid of exp_h9_tiled_da.py (training dx = 44/128, patch 16 points);
the 44^2 row is checked against the run's own JSON (n_sites, args). 1D rows (unchanged, App. E's 1D
results) come from the 1D run JSONs.
"""
import json

from _style import ART, EXP, ROOT

D = EXP / "da2d"
OUT = ROOT / "docs/paper1/tables"
C, PATCH, STRIDE, DX = 12, 16, 8, 44.0 / 128
inputs = []
rows = ["% Generated by scripts/paper_figures/tabE_p2.py -- do not edit by hand."]
for L in (44, 66, 88, 220, 330, 440):
    NX = round(L / DX)
    ns = NX // PATCH
    d = C * ns * ns
    m = (NX // STRIDE) ** 2
    rows.append(f"2D KS & ${L}^2$ & ${NX}^2$ & ${ns}^2$ & {C} & {d} & 4 & $(0,0),(8,0),(0,8),(8,8)$ & "
                f"{STRIDE} & {STRIDE * DX:.3f} & {m} \\\\")
ref = json.loads((D / "h9_I33_d10_T4_s0.json").read_text())
inputs.append("artifacts/experiments/da2d/h9_I33_d10_T4_s0.json")
a = ref["args"]
assert a["obs_stride"] == STRIDE and a["n_tilings"] == 4 and a["L"] == 44.0, a
for L in (200, 400):
    p = ART / f"da_pff_ltransfer_d1_pff_L{L}_gaspari_cohn_nens64.json"
    inputs.append(str(p.relative_to(ROOT)))
    j = json.loads(p.read_text())
    rows.append(f"1D KS & $L={L}$ & {j['new_NX']} & {j['new_n_sites']} & 3 & {j['new_n_sites'] * 3} & 1 & --- & "
                f"{j['obs_stride']} & {j['obs_spacing_units']:.3f} & {j['new_NX'] // j['obs_stride']} \\\\")
(OUT / "tabE_p2_networks.tex").write_text("\n".join(rows) + "\n")
(OUT / "tabE_p2_networks.meta.json").write_text(json.dumps({"inputs": inputs}, indent=2))
print("\n".join(rows))
