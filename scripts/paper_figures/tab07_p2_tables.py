"""Part II tables (Block K2a, K2b; 2026-10-10), model p7c12d10_ks2d, Part II filter settings
(per-site local ETKF, GC half-width 1.5 sites, RTPS 0.7, stride 8, 64 members per tiling, 100 cycles,
steady state = cycles 51-100), physical RMSE in field units, from artifacts/experiments/da2d/h9_*.json.

tab07_p2_sizes.tex (K2a): one row per domain size: d, RMSE with 1 tiling, RMSE with 4 tilings (seed 0;
  further seeds after commas), spread/error (4 tilings, seed 0), interpolation of the observations,
  decoder floor with 1 and 4 tilings, free-run error.
tab07_p2_members.tex (K2b): three blocks
  (i)  members per tiling N, 4 tilings, at 44^2 and 220^2: RMSE (spread/error);
  (ii) a fixed total of 64 members split over K tilings, seeds 0-2;
  (iii) four ensembles of 64 on four shifted tilings vs on ONE tiling (control: same members, same
       blend, no offsets), seeds 0-2;
  (iv) number of tilings K with Hann weights (and K = 4 uniform), 64 members per tiling, seed 0.
Missing runs are printed as ---. Writes a .meta.json next to each table with its inputs.
"""
import json

from _style import EXP, ROOT

D = EXP / "da2d"
TAB = ROOT / "docs/paper1/tables"
inputs = {"sizes": [], "members": []}


def st(tag, which):
    p = D / f"h9_{tag}.json"
    if not p.exists():
        return None
    inputs[which].append(str(p.relative_to(ROOT)))
    s = json.loads(p.read_text())["steady"]
    if s.get("diverged_at_cycle") is not None:
        return {"diverged": s["diverged_at_cycle"]}
    return s


def f3(x):
    return "---" if x is None else f"{x:.3f}"


def rm(s, key="blend", cal=False):
    if s is None:
        return "---"
    if "diverged" in s:
        return f"div.\\ ({s['diverged']})"
    return f"{s[key]:.3f}" + (f" ({s['calib_blend']:.2f})" if cal else "")


# ---------------- K2a: sizes ----------------
SIZES = {  # size: (1-tiling tag, [4-tiling tags by seed])
    44: ("I33_d10_T1_s0", ["I33_d10_T4_s0", "I33_d10_T4_s1", "I33_d10_T4_s2"]),
    66: ("K1l_L66_T1_N64", ["K1l_L66_T4_N64"]),
    88: ("D10_L88_I1_T1", ["D10_L88_I1_T4"]),
    220: ("D10_L220_I1_T1", ["D10_L220_I1_T4", "D10_L220_I1_T4_s1"]),
    330: ("D10_L330_I1_T1", ["D10_L330_I1_T4", "D10_L330_I1_T4_s1"]),
    440: ("D10_L440_I1_T1", ["D10_L440_I1_T4"]),
}
rows = ["% Generated by scripts/paper_figures/tab07_p2_tables.py -- do not edit by hand."]
summary = {}
for L, (t1, t4s) in SIZES.items():
    s1 = st(t1, "sizes")
    s4 = [st(t, "sizes") for t in t4s]
    s40 = s4[0]
    if s1 is None and s40 is None:
        continue
    d = 12 * (L * 8 // 44) ** 2
    k4 = ", ".join(rm(s) for s in s4 if s is not None) or "---"
    ref = s40 if s40 is not None and "diverged" not in s40 else s1
    ok4 = s40 is not None and "diverged" not in s40
    cal = f"{s40['calib_blend']:.2f}" if ok4 else "---"
    rows.append(f"${L}^2$ & {d} & {rm(s1)} & {k4} & {cal} & {f3(ref['interp'] if ref else None)} & "
                f"{f3(s1['floor1'] if s1 else None)} & {f3(s40['floorK'] if ok4 else None)} & "
                f"{f3(ref['free'] if ref else None)} \\\\")
    summary[L] = {"d": d, "K1": s1 and s1.get("blend"), "K4": [s and s.get("blend") for s in s4]}
(TAB / "tab07_p2_sizes.tex").write_text("\n".join(rows) + "\n")
(TAB / "tab07_p2_sizes.meta.json").write_text(json.dumps({"inputs": inputs["sizes"], "summary": summary}, indent=2))

# ---------------- K2b: members and tilings ----------------
rows = ["% Generated by scripts/paper_figures/tab07_p2_tables.py -- do not edit by hand.",
        "\\multicolumn{5}{l}{\\emph{(i) members per tiling, 4 tilings}} \\\\",
        "$N$ per tiling & \\multicolumn{2}{c}{$44^2$} & \\multicolumn{2}{c}{$220^2$} \\\\"]
for N in (8, 16, 32, 64, 128):
    a = st("I33_d10_T4_s0" if N == 64 else f"D10_L44_I3_N{N}", "members")
    b = st("D10_L220_I1_T4" if N == 64 else f"D10_L220_I3_N{N}", "members")
    rows.append(f"{N} & \\multicolumn{{2}}{{c}}{{{rm(a, cal=True)}}} & \\multicolumn{{2}}{{c}}{{{rm(b, cal=True)}}} \\\\")
rows += ["\\hline", "\\multicolumn{5}{l}{\\emph{(ii) a fixed total of 64 members, $44^2$}} \\\\",
         "tilings $\\times$ members & seed 0 & seed 1 & seed 2 & spread/error \\\\"]
for lab, tag in (("$1\\times64$", "D10_L44_I2_T1_N64"), ("$2\\times32$", "D10_L44_I2_T2_N32"),
                 ("$4\\times16$", "D10_L44_I2_T4_N16")):
    ss = [st(f"{tag}_s{k}", "members") for k in range(3)]
    cals = [s["calib_blend"] for s in ss if s and "diverged" not in s]
    rows.append(f"{lab} & " + " & ".join(rm(s) for s in ss)
                + f" & {min(cals):.2f}--{max(cals):.2f} \\\\" if cals else f"{lab} & --- & --- & --- & --- \\\\")
rows += ["\\hline", "\\multicolumn{5}{l}{\\emph{(iii) four ensembles of 64: shifted tilings vs one tiling, $44^2$}} \\\\",
         "ensembles & seed 0 & seed 1 & seed 2 & spread/error \\\\"]
for lab, tags in (("4 shifted tilings", [f"I33_d10_T4_s{k}" for k in range(3)]),
                  ("4 on one tiling", [f"K2b_ctrl_T4_s{k}" for k in range(3)])):
    ss = [st(t, "members") for t in tags]
    cals = [x["calib_blend"] for x in ss if x and "diverged" not in x]
    rows.append(f"{lab} & " + " & ".join(rm(x) for x in ss)
                + (f" & {min(cals):.2f}--{max(cals):.2f} \\\\" if cals else " & --- \\\\"))
rows += ["\\hline", "\\multicolumn{5}{l}{\\emph{(iv) number of tilings, 64 members each, $44^2$, seed 0}} \\\\",
         "$K$ & RMSE & spread/error & decoder floor & \\\\"]
for lab, tag in (("1", "I33_d10_T1_s0"), ("2", "D10_L44_I4_T2"), ("4", "I33_d10_T4_s0"),
                 ("4, uniform", "D10_L44_I4_T4u"), ("16", "D10_L44_I4_T16")):
    s = st(tag, "members")
    rows.append(f"{lab} & {rm(s)} & " + ("---" if s is None else f"{s['calib_blend']:.2f}")
                + f" & {f3(s and s.get('floorK'))} & \\\\")
(TAB / "tab07_p2_members.tex").write_text("\n".join(rows) + "\n")
(TAB / "tab07_p2_members.meta.json").write_text(json.dumps({"inputs": inputs["members"]}, indent=2))
print((TAB / "tab07_p2_sizes.tex").read_text()); print((TAB / "tab07_p2_members.tex").read_text())
