"""Paper II table (Z20 W2, 2026-10-20): the cost of the nonlinear decoder, 2D KS 44^2, seeds 0-2,
steady state (cycles 51-100), field units.

Rows: the paper's per-site filter (E1), relinearized with 2 and 3 Gauss-Newton iterations (E3), the kernel particle
flow filter (E6/E6b: alpha = 1/N, RTPS 0, model noise 0.01, 4 x 64 and 4 x 32), the oracle-forecast latent filter, incremental and projected (E4, best seed-0
RTPS), the perfect-model physical-space LETKF with 64 and 256 members (E4), and the reconstruction floor of the
4-tiling blend (truth encoded and decoded, no assimilation). Columns: analysis error on seeds 0/1/2, mean spread/error,
nonlinearity index eta_o (Eq. nl_index, forecast ensemble), observation-space consistency ratio of the blended prior.
Missing runs print as ---. Writes tables/nonlinear.tex and a .meta.json with the numbers the text quotes.
"""
import glob
import json

from _style import EXP, ROOT, write_table

D = EXP / "da2d"
inputs = []


def load(name):
    p = D / f"{name}.json"
    if not p.exists():
        return None
    inputs.append(str(p.relative_to(ROOT)))
    d = json.loads(p.read_text())
    s = d["steady"]
    if s.get("diverged_at_cycle") is not None:
        return {"diverged": s["diverged_at_cycle"]}
    if name.startswith("i11_"):  # physical-space filter: different keys
        return {"blend": s["analysis"], "calib_blend": s["calib"]}
    return s


def best_tag(pattern, key="blend"):
    """Among seed-0 runs matching `pattern` (h9_<...>_s0.json), the one with the lowest key; returns the stem
    without '_s0'."""
    cands = {}
    for f in glob.glob(str(D / f"h9_{pattern}_s0.json")):
        s = json.loads(open(f).read())["steady"]
        if s.get("diverged_at_cycle") is None:
            cands[f.split("h9_")[1][:-8]] = s[key]
    return min(cands, key=cands.get) if cands else None


def f3(x):
    return "---" if x is None else f"{x:.3f}"


def f2(x):
    return "---" if x is None else f"{x:.2f}"


def row(label, stem, prefix="h9_", key="blend", errors_only=False):
    runs = [load(f"{prefix}{stem}_s{s}") if stem else None for s in range(3)]
    ok = [r for r in runs if r and "diverged" not in r]
    errs = " / ".join("div." if (r and "diverged" in r) else f3(r[key] if r else None) for r in runs)
    mean = lambda k: sum(r[k] for r in ok) / len(ok) if ok and all(k in r for r in ok) else None  # noqa: E731
    vals = {"err": [r[key] if r and "diverged" not in r else None for r in runs], "calib": mean("calib_blend"),
            "eta_o": mean("nl_eta_o"), "chi2_blend": mean("nl_chi2_blend")}
    summary[label] = vals
    if errors_only:
        return f"{label} & {errs} & --- & --- & --- \\\\"
    return f"{label} & {errs} & {f2(vals['calib'])} & {f3(vals['eta_o'])} & {f2(vals['chi2_blend'])} \\\\"


summary = {}
e4_inc = best_tag("z20_e4_increment_r*")
e4_inc = e4_inc if e4_inc and "_N16" not in e4_inc and "_it3" not in e4_inc else None
e4_pro = best_tag("z20_e4_project_r*")
e4_pro = e4_pro if e4_pro and "_N16" not in e4_pro else None
e6 = best_tag("z20_e6_N32_a*")
rows = ["% Generated by scripts/paper_figures/tab_nonlinear.py -- do not edit by hand.",
        row("Per-site filter (this paper)", "z20_e1"),
        row("\\quad relinearized, 2 iterations", "z20_e3_it2"),
        row("\\quad relinearized, 3 iterations", "z20_e3_it3"),
        row("Kernel particle flow filter", "z20_e6b_N64_mn0.01"),
        row("\\quad $4\\times32$ members", "z20_e6b_N32_mn0.01"),
        "\\hline",
        row("Oracle forecast, incremental", e4_inc),
        row("Oracle forecast, projected", e4_pro),
        row("Physical-space LETKF, perfect model, 64", "z20_e4_phys_c24_r0", prefix="i11_"),
        row("Physical-space LETKF, perfect model, 256", "z20_e4_phys_c24_r0_N256", prefix="i11_"),
        row("Reconstruction floor, 4 tilings", "z20_e1", key="floorK", errors_only=True)]
write_table("tab_nonlinear", "\n".join(rows) + "\n", inputs, summary=summary,
            chosen={"e4_increment": e4_inc, "e4_project": e4_pro, "e6": e6})
print("\n".join(rows))
