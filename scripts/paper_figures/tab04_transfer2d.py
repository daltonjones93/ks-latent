"""Table IV (canonical 2D models, zero-shot), generated from the crop evaluation JSONs and
the truth registry. Entry: mean model D_KY over ICs (number of ICs) and mean of per-IC
relative errors (Kolmogorov alpha=0.05 at 1x: each IC against its matched-IC truth;
elsewhere against the mean over truth runs). Writes docs/paper1/tables/tab04_transfer2d.tex."""
import json

import numpy as np

from _style import EXP, MAIN_A01, ROOT, write_table
from _truths import runs

ROWS = [("2D KS", "p7b_ks2d", "ks2d", [("1.0", 1.0), ("1.5", 1.5), ("2.0", None)], (0, 1, 2)),
        ("Kolm., $\\alpha=0.1$", MAIN_A01, "kolm0.1", [("1", 1), ("2", 2), ("3", 3)], (0, 1, 2)),
        ("Kolm., $\\alpha=0.05$", "c19_e0d0_c6", "kolm0.05", [("1", 1), ("2", 2), ("3", 3)], (0, 1, 2)),
        ("Kolm., $\\alpha=0.025$", "k_xs0025", "kolm0.025", [("1", 1), ("2", 2), ("3", 3)], (0, 1, 2))]
lines, inputs = ["% Generated by scripts/paper_figures/tab04_transfer2d.py -- do not edit by hand."], []
for label, tag, tsys, sizes, seeds in ROWS:
    cells = []
    for sfile, tsize in sizes:
        vals = []
        for s in seeds:
            p = EXP / f"crop/{tag}_x{sfile}_seed{s}.json"
            if p.exists():
                vals.append((s, json.loads(p.read_text())["model_D_KY"])); inputs.append(str(p.relative_to(ROOT)))
        m = np.mean([v for _, v in vals])
        if tsize is None:
            cells.append(f"{m:.1f} ({len(vals)}), no truth")
            continue
        tr = runs(tsys, tsize); inputs += [r["file"] for r in tr]
        if tsys == "kolm0.05" and tsize == 1:
            ref = {r["seed"]: r["D_KY"] for r in tr}
            errs = [abs(v - ref[s]) / ref[s] for s, v in vals]
        else:
            t = np.mean([r["D_KY"] for r in tr]); errs = [abs(v - t) / t for _, v in vals]
        cells.append(f"{m:.1f} ({len(vals)}), ${100*np.mean(errs):.1f}\\%$")
    sizes_txt = "$44^2$, $66^2$, $88^2$" if tsys == "ks2d" else "$1\\times,2\\times,3\\times$"
    lines.append(f"{label} & {sizes_txt} & " + " & ".join(cells) + " \\\\")
write_table("tab04_transfer2d", "\n".join(lines) + "\n", inputs, main_alpha01_model=MAIN_A01)
print("\n".join(lines))
