"""Paper I Table IV (transfer in two dimensions, both training routes) and Table V (leading
exponent, model vs truth), generated from the crop evaluation JSONs and the truth registry.

Rewrite of 2026-10-13 (Paper I, Block Z11/Z3; referee M1-M4, M7): rows are grouped by system and
training route -- a small periodic box (route a: 2D KS 44^2 box, Kolmogorov 2pi x 2pi box) and
windows of one large simulation (route b) -- plus the trivial extensive baseline (truth at the
first size times the area or width ratio). Each cell: mean model D_KY over all evaluations
(training seeds x initial conditions; number in parentheses), the signed error of that mean against
the reference, and the range of the per-evaluation signed errors in brackets. Reference: mean over
the truth runs in `_truths.py`, except Kolmogorov alpha=0.05 at 1x, where each evaluation is scored
against the run from its own initial condition (then the "mean" error is the mean of the per-IC
signed errors). 2D KS at 88^2 is scored against its truth once that run exists; until then the cell
gives the model's dimension per 44^2 box.

Writes <PAPER_TABLES>/transfer2d.tex and lambda1.tex (+ .meta.json each). PAPER_TABLES must point
at the split paper (docs/paperI/tables); this script refuses to write into docs/paper1.
"""
import json

import numpy as np

from _style import EXP, MAIN_A01, ROOT, TABLES, write_table
from _truths import runs

if "docs/paper1/" in str(TABLES) + "/":
    raise SystemExit("tab04_transfer2d.py (Paper I rewrite) writes only into docs/paperI; set PAPER_TABLES")

KS_SIZES = [("1.0", 1.0), ("1.5", 1.5), ("2.0", 2.0)]
K_SIZES = [("1", 1), ("2", 2), ("3", 3)]
C2 = [f"r13_C2_ks2d_s44big_k48_seed{s}" for s in (0, 1, 2)]
# (system label, route label, [tags], truth system, sizes)
ROWS = [
    ("2D KS", "small box ($44^2$), 3 seeds", C2, "ks2d", KS_SIZES),
    ("", "windows of $264^2$", ["p7b_ks2d"], "ks2d", KS_SIZES),
    # Referee 2 (A4, 2026-10-13): every small-box model is reported, the same way at both drags -- the
    # recipe-C model with three initial conditions, and the other seeds and recipes (C2: four times the box
    # data and longer rollouts; C3: C2 with the whole box scored) pooled in a second row.
    ("Kolm., $\\alpha=0.1$", "small box, recipe C, seed 0", ["r12_c6_a01_s1x_r3"], "kolm0.1", K_SIZES),
    ("", "small box, seeds 1--2, C2, C3", ["r12_c6_a01_s1x_r3_seed1", "r12_c6_a01_s1x_r3_seed2",
                                         "r14_KC2_a0.1_seed0", "r14_KC3_a0.1_seed0"], "kolm0.1", K_SIZES),
    ("", "windows of $16\\times$", [MAIN_A01], "kolm0.1", K_SIZES),
    ("Kolm., $\\alpha=0.05$", "small box, recipe C", ["r4k_c6_a005_s1x_r3"], "kolm0.05", K_SIZES),
    ("", "small box, C2, C3", ["r14_KC2_a0.05_seed0", "r14_KC3_a0.05_seed0"], "kolm0.05", K_SIZES),
    ("", "windows of $16\\times$", ["c19_e0d0_c6"], "kolm0.05", K_SIZES),
    ("Kolm., $\\alpha=0.025$", "windows of $16\\times$", ["k_xs0025"], "kolm0.025", K_SIZES),
]
inputs: list[str] = []


def evals(tags, sfile):
    out = []
    for tag in tags:
        for ic in (0, 1, 2):
            p = EXP / f"crop/{tag}_x{sfile}_seed{ic}.json"
            if p.exists():
                d = json.loads(p.read_text())
                out.append((ic, d["model_D_KY"], d["model_lambda1"]))
                inputs.append(str(p.relative_to(ROOT)))
    return out


def truth(tsys, tsize):
    tr = runs(tsys, tsize)
    inputs.extend(r["file"] for r in tr)
    return tr


def pct(x):
    return f"{x:+.1f}".replace("-", "$-$").replace("+", "$+$")


def cell(tags, tsys, sfile, tsize):
    ev = evals(tags, sfile)
    if not ev:
        return "---"
    v = np.array([x for _, x, _ in ev])
    tr = truth(tsys, tsize)
    if not tr:  # 2D KS 88^2 before its truth exists: dimension per 44^2 box
        return f"{v.mean():.1f} ({len(v)}), {v.mean() / 4:.1f}/box"
    if tsys == "kolm0.05" and tsize == 1:
        ref = {r["seed"]: r["D_KY"] for r in tr}
        e = np.array([100 * (x - ref[ic]) / ref[ic] for ic, x, _ in ev])
        mean_err = e.mean()
    else:
        t = float(np.mean([r["D_KY"] for r in tr]))
        e = 100 * (v - t) / t
        mean_err = 100 * (v.mean() - t) / t
    rng = f" [{pct(e.min())},\\,{pct(e.max())}]" if len(v) > 1 else ""
    return f"{v.mean():.1f} ({len(v)}), {pct(mean_err)}\\%{rng}"


lines = ["% Generated by scripts/paper_figures/tab04_transfer2d.py -- do not edit by hand."]
for i, (sysl, route, tags, tsys, sizes) in enumerate(ROWS):
    if sysl and i:
        lines.append("\\hline")
    if sysl:  # trivial extensive baseline first: truth at the first size times the size ratio
        t1 = float(np.mean([r["D_KY"] for r in truth(tsys, sizes[0][1])]))
        ratio = [1.0, 2.25, 4.0] if tsys == "ks2d" else [1.0, 2.0, 3.0]
        cells = []
        for (sf, ts), q in zip(sizes, ratio):
            tr = truth(tsys, ts)
            if q == 1.0:
                cells.append(f"{t1:.1f} (truth)")
            elif tr:
                t = float(np.mean([r["D_KY"] for r in tr]))
                cells.append(f"{t1 * q:.1f}, {pct(100 * (t1 * q - t) / t)}\\%")
            else:
                cells.append(f"{t1 * q:.1f}")
        lines.append(f"{sysl} & extensive baseline & " + " & ".join(cells) + " \\\\")
    lines.append(f" & {route} & " + " & ".join(cell(tags, tsys, sf, ts) for sf, ts in sizes) + " \\\\")
write_table("tab04_transfer2d", "\n".join(lines) + "\n", inputs, main_alpha01_model=MAIN_A01)
print("\n".join(lines))

# ---------------- Table V: leading exponent ----------------
L1 = [  # system label, size label, truth system, size key, small-box tags, window tags
    ("2D KS", "$44^2$", "ks2d", ("1.0", 1.0), C2, ["p7b_ks2d"]),
    ("", "$66^2$", "ks2d", ("1.5", 1.5), C2, ["p7b_ks2d"]),
    ("", "$88^2$", "ks2d", ("2.0", 2.0), C2, ["p7b_ks2d"]),
    ("Kolm., $\\alpha=0.1$", "$1\\times$", "kolm0.1", ("1", 1), ["r12_c6_a01_s1x_r3"], [MAIN_A01]),
    ("", "$2\\times$", "kolm0.1", ("2", 2), ["r12_c6_a01_s1x_r3"], [MAIN_A01]),
    ("", "$3\\times$", "kolm0.1", ("3", 3), ["r12_c6_a01_s1x_r3"], [MAIN_A01]),
    ("Kolm., $\\alpha=0.05$", "$1\\times$", "kolm0.05", ("1", 1), ["r4k_c6_a005_s1x_r3"], ["c19_e0d0_c6"]),
    ("", "$2\\times$", "kolm0.05", ("2", 2), ["r4k_c6_a005_s1x_r3"], ["c19_e0d0_c6"]),
    ("", "$3\\times$", "kolm0.05", ("3", 3), ["r14_KC2_a0.05_seed0"], ["c19_e0d0_c6"]),
    ("Kolm., $\\alpha=0.025$", "$1\\times$", "kolm0.025", ("1", 1), [], ["k_xs0025"]),
    ("", "$2\\times$", "kolm0.025", ("2", 2), [], ["k_xs0025"]),
    ("", "$3\\times$", "kolm0.025", ("3", 3), [], ["k_xs0025"]),
]
lines = ["% Generated by scripts/paper_figures/tab04_transfer2d.py -- do not edit by hand."]
for sysl, sl, tsys, (sf, ts), box, win in L1:
    if sysl and lines[-1].endswith("\\\\"):
        lines.append("\\hline")
    tl = np.array([r["lambda1"] for r in truth(tsys, ts)])
    tcell = f"{tl.mean():.3f}" + (f" [{tl.min():.3f}--{tl.max():.3f}]" if len(tl) > 1 else "")
    cells = []
    for tags in (box, win):
        ev = evals(tags, sf)
        if not ev:
            cells.append("---")
            continue
        ml = np.array([x for _, _, x in ev])
        cells.append(f"{ml.mean():.3f} ({len(ml)}), {pct(100 * (ml.mean() - tl.mean()) / tl.mean())}\\%")
    lines.append(f"{sysl} & {sl} & {tcell} & " + " & ".join(cells) + " \\\\")
write_table("tab04_lambda1", "\n".join(lines) + "\n", inputs, main_alpha01_model=MAIN_A01)
print("\n".join(lines))
